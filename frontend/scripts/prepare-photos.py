"""Make the web copies of the photos behind the home page bouquet.

Reads every image in frontend/assets/ (the originals, which never ship) and
writes, for each one:

- frontend/public/photos/<name>.webp: turned upright, longest side at most
  MAX_SIDE, and with all metadata dropped. The phone originals carry GPS
  coordinates, so nothing from their EXIF may reach the public site.
- an entry in frontend/src/lib/photos.ts with its size, so the page can lay
  the photos out before any of them has loaded.

Run from frontend/ after adding, removing or renaming a photo:

    python scripts/prepare-photos.py

Needs Pillow (pip install Pillow). It is not a dependency of the app itself.
"""

from pathlib import Path

from PIL import Image, ImageOps

FRONTEND = Path(__file__).resolve().parent.parent
SOURCE = FRONTEND / "assets"
OUT = FRONTEND / "public" / "photos"
MANIFEST = FRONTEND / "src" / "lib" / "photos.ts"

# The photos are shown small and faded, at most ~300 CSS px wide; 720 px is
# sharp enough at 2x and keeps the whole set around a megabyte.
MAX_SIDE = 720
QUALITY = 72


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*.webp"):
        stale.unlink()

    entries = []
    total = 0
    for path in sorted(SOURCE.iterdir()):
        if path.suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp", ".heic"}:
            continue
        with Image.open(path) as original:
            image = ImageOps.exif_transpose(original).convert("RGB")
        image.thumbnail((MAX_SIDE, MAX_SIDE), Image.Resampling.LANCZOS)
        target = OUT / f"{path.stem}.webp"
        # No exif= argument, so Pillow writes no metadata at all.
        image.save(target, "WEBP", quality=QUALITY, method=6)
        total += target.stat().st_size
        entries.append((path.stem, image.width, image.height))
        print(f"{path.name:32} -> {target.name:32} {image.width}x{image.height}")

    lines = [
        "/**",
        " * The photos behind the home page bouquet, served from public/photos/.",
        " *",
        " * Generated by scripts/prepare-photos.py from frontend/assets/. Do not",
        " * edit by hand; rerun the script instead.",
        " */",
        "",
        "export interface Photo {",
        "  src: string;",
        "  width: number;",
        "  height: number;",
        "}",
        "",
        "export const PHOTOS: readonly Photo[] = [",
    ]
    for stem, width, height in entries:
        lines.append(f"  {{ src: '/photos/{stem}.webp', width: {width}, height: {height} }},")
    lines += ["];", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(entries)} photos, {total // 1024} KB in all")


if __name__ == "__main__":
    main()
